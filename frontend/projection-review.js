export function projectionReview(relation) {
  if (!relation.interfaceId || relation.internal || relation.reference) return null;
  const reason = rejected[relation.interfaceId];
  return reason ? {rejected:true, label:'端点不匹配', reason}
    : {rejected:false, label:'待核验映射', reason:verification[relation.interfaceId]||'该关系由产品联动推导，需核对功能端点、触发条件与字段映射。'};
}
